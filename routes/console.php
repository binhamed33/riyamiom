<?php

use Illuminate\Support\Facades\Schedule;

// النسخة اليومية — الساعة ٢ ظهراً بتوقيت مسقط.
//
// التوقيت مكتوب بمنطقته صراحةً لا محسوباً في الرأس: الخادم على UTC،
// وكان الجدول يقول 3:00 والتعليق يقول شيئاً آخر، فأي تعديل لاحق
// يحتاج طرحاً وجمعاً — ومن يخطئ فيه لا يكتشفه إلا حين يبحث عن نسخة
// فلا يجدها. ->timezone يجعل المكتوب هو المقصود.
Schedule::command('backup:daily')->dailyAt('14:00')->timezone('Asia/Muscat');

// إقفال سجلّات الحضور المفتوحة — آخر الليل بتوقيت مسقط.
//
// الانصراف لا يُسجَّل إلا بضغط «تسجيل خروج»، والموظّف يُغلق المتصفّح
// ويمضي فيبقى سجلّه مفتوحاً بلا دقائق. يُقفَل هنا بوقت آخر نشاطٍ معروف
// له، لا بساعة تشغيل الأمر.
Schedule::command('hr:close-attendance')->dailyAt('23:50')->timezone('Asia/Muscat');

// سقفُ المناوبة كلَّ ساعة: من مضى على حضوره ثمانٍ بلا انصراف يُقفل
// سجلُّه. ولو انتُظر به آخرُ الليل لظهر «حاضراً» طولَ اليوم، ولبقي
// سجلُّ من دخل الأحد مفتوحاً إلى الخميس.
Schedule::command('hr:close-attendance --cap')->hourly()->withoutOverlapping();

// التذكير الشهري بالنسخة — أول كل شهر ٩ صباحاً بتوقيت مسقط.
//
// مديرٌ لا يعرف أين نسخته ولا كيف يستعيدها يكتشف ذلك يومَ الكارثة.
// (النسخ النصف-ساعية أُلغيت بسياسة «نسخة واحدة تتجدد»: كانت تراكم
// عشرين ملفاً من بيانات الموكلين لكل مكتب — مساحةً وسطحَ تسريب.)
Schedule::command('backup:remind')->monthlyOn(1, '09:00')->timezone('Asia/Muscat');

// Server status to Discord every 5 minutes
Schedule::command('discord:status')->everyFiveMinutes();

// Staff presence board to Discord every 5 minutes
Schedule::command('discord:staff-status')->everyFiveMinutes();

// إشعارات الاشتراك — لمدير المكتب فقط، ٨ صباحاً بتوقيت مسقط
Schedule::command('subscription:notices')->dailyAt('8:00')->timezone('Asia/Muscat');

// محرك الأتمتة — يعمل كل ساعة، ويخرج فوراً ما لم يُفعَّل من لوحة المطور
Schedule::command('mudawala:automation')->hourly();

// نبضة إلى لوحة مُداوَلة — خامدة ما لم يُضبط الربط
// كل ربع ساعة لا كل ساعة: تغييرُ باقةٍ من اللوحة يسري هنا خلال دقائق،
// والنبضة رخيصة — طلب واحد صغير.
Schedule::command('panel:heartbeat')->everyFifteenMinutes();

// شبكة أمان الاقتراحات: ما لم يصل اللوحة يُعاد إرساله — خامد إن لم
// يكن المكتب مربوطاً.
Schedule::command('suggestions:retry-delivery')->hourly()->withoutOverlapping();

// قناة العودة: حالة الاقتراح وردّ المطوّر تُجلب من اللوحة إلى المكتب،
// فيرى الموظّف مصير اقتراحه ويصله إشعار بلغته — خامدة إن لم يكن
// المكتب مربوطاً.
Schedule::command('suggestions:sync-replies')->everyFifteenMinutes()->withoutOverlapping();

// ═══ عاملُ طابور البريد ═══
//
// لا يعمل على هذا الخادم عاملُ طابورٍ دائم (لا supervisor ولا systemd)،
// فكلُّ ما يُلقى في الطابور يبقى فيه إلى الأبد. ولمّا صار البريد
// مؤجَّلاً — كي لا تنتظر «حفظ القضية» مصافحةَ Gmail — لزم من يحمله.
//
// فالمجدولُ نفسه هو العامل: كلَّ دقيقة يقوم عاملٌ يصرّف الطابور ثمّ
// يخرج بسقفٍ زمنيّ دون الدقيقة كي لا تتراكب العمليات،
// و withoutOverlapping حارسٌ ثانٍ لو تأخّرت واحدة.
//
// والطابوران معاً — «mail» أولاً ثم «default».
//
// ولم يكن كذلك في أول الأمر: صُرِّف طابور البريد وحده، فبقي الطابور
// العام بلا قارئ. ولم يُلحَظ لأنّ QUEUE_CONNECTION كان sync في المكاتب،
// فمهمّةُ توصيل الاقتراحات تُنفَّذ داخل الطلب ولا تمرّ بطابور أصلاً.
// فلمّا صار database — وهو الصواب كي لا ينتظر «حفظ القضية» مصافحةَ
// Gmail — نزلت الاقتراحاتُ طابوراً لا أحد يقرؤه، فتوقّف تسليمُها.
//
// ترتيبُ الأسماء أولويّةٌ لا تعداد: ما في «mail» يخرج قبل ما في
// «default»، فلا يؤخّر إشعارَ موكّلٍ عملٌ خلفيّ طويل.
//
// ═══ ولا يخرج العاملُ والمؤجَّلُ ينتظر ═══
//
// كان ‎--stop-when-empty‎: يخرج العاملُ فورَ خلوّ الطابور ممّا هو
// **جاهزٌ الآن**، والمؤجَّلُ ليس جاهزاً. فرسالةٌ حجزها حارسُ الإيقاع
// عشرين ثانيةً لا يلتقطها أحدٌ حتى تشغيلةِ رأس الدقيقة التالية —
// فيصير التأخيرُ الفعليّ دقيقةً كاملةً بدل العشرين، وتُقرأ «تأخّرت».
//
// وبحذفه يبقى العاملُ حيّاً خمساً وخمسين ثانيةً يستطلع كلَّ ثانية،
// فيرسل المؤجَّلَ في ثانيتِه لا في دقيقتِه. و‎--max-time‎ يضمن خروجَه،
// و‎withoutOverlapping‎ يمنع عاملَين معاً.
Schedule::command('queue:work --queue=mail,default --tries=3 --max-time=55 --sleep=1')
    ->everyMinute()
    ->withoutOverlapping()
    ->runInBackground();

// الرسائل التي أخفقت محاولاتها الثلاث تبقى في failed_jobs. تُنظَّف
// القديمة أسبوعياً كي لا يكبر الجدول بلا حدّ — والأسبوع يكفي لمن
// يريد أن يقرأ سبب الإخفاق.
Schedule::command('queue:prune-failed --hours=168')->weekly();

/*
| واتساب
|
| ‏sweep حارسٌ لا مُنفِّذ: الويبهوك يقيّد الحدث ثمّ يدفعه إلى الطابور،
| فإن كان الطابور متوقّفاً لحظتَها بقي الحدث مقيَّداً بلا معالجة. هذا
| الأمرُ يلتقط ما مضى عليه خمسُ دقائق ولم يُعالَج — فرسالةُ موكّلٍ لا
| تضيع لأنّ عاملاً تعثّر، ثمّ يقلّم السجلّ القديم كي لا يكبر بلا حدّ.
*/
Schedule::command('whatsapp:sweep')->everyFiveMinutes()->withoutOverlapping();

// تذكيرُ المواعيد — كلَّ ساعة، ونافذتُه من الآن إلى حدّ التذكير
// المضبوط، و`reminded_at` يمنع تكرارَ الرسالة على الموعد نفسِه.
Schedule::command('appointments:remind')->hourly()->withoutOverlapping();

// تذكيرُ الجلسات — كلَّ ساعة، والأمرُ نفسه يقرّر أيَّ جلساتٍ حان
// تذكيرُها وفق إعداد المكتب، ويرفض التكرار على نفس الجلسة.
Schedule::command('whatsapp:session-reminders')->hourly()->withoutOverlapping();

// حالةُ القوالب تتغيّر عند Meta بلا إشعارٍ لنا: قالبٌ معتمَدٌ قد
// يُوقَف. المزامنةُ اليومية تمنع أن نعرض «معتمَد» لما لم يعد كذلك.
Schedule::command('whatsapp:sync-templates')->dailyAt('03:30')->timezone('Asia/Muscat');

// روابطُ الدخول المنتهية تُقلَّم: صفٌّ لكلّ إشعارٍ أُرسل، ولو بقيت
// كلُّها لنمت بلا حدّ. والمقلَّمُ منتهٍ أصلاً — لا يفتح شيئاً.
Schedule::call(function () {
    \App\Services\ClientPortal\PortalLinks::prune();
})->dailyAt('03:45')->timezone('Asia/Muscat')->name('portal-links-prune');

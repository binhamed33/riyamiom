<?php

namespace App\Support;

/**
 * مدّةٌ تُقرأ كما هي مكتوبة.
 *
 * ═══ ما وقع على شاشة المالك ═══
 *
 * عمودُ «المدة» في سجلّ الحضور كان يعرض:
 *
 *     س 15د 6        ⇽ والمقصود «6 س 15 د»
 *     س 44د 5        ⇽ والمقصود «5 س 44 د»
 *
 * الرقمُ يقفز إلى آخر السطر. والسببُ ليس خطأً في الحساب: الخليّة كانت
 * ‏dir="ltr" ونصُّها يخلط أرقاماً لاتينيّةً بحرفين عربيّين. وخوارزميّةُ
 * الاتّجاهين في المتصفّح تقسم النصَّ المختلط إلى مقاطع وتعيد ترتيبها،
 * فيخرج ما لم يُكتب — بلا خطأٍ يُبلَّغ عنه ولا شيءٍ يُشتكى منه إلا أنّ
 * القارئ لا يفهم.
 *
 * ═══ ولماذا هنا لا في ثلاث خلايا ═══
 *
 * النصُّ كان يُبنى بيده في ثلاثة مواضع من القالب نفسِه، متطابقةً حرفاً
 * بحرف. فمن أصلح واحدةً ترك اثنتين — وهذا ما يجعل العطبَ يعود.
 */
class Duration
{
    /**
     * ‏«6 س 15 د» · «45 د» · «6 س» · «أقلّ من دقيقة» · «—»
     *
     * والصفرُ يُقال بلغته: «0 س 0 د» رقمان صحيحان لا يعنيان شيئاً
     * لقارئ — والموظّفُ الذي سجّل حضورَه وانصرافَه في الدقيقة نفسِها
     * أوضحُ عنه أن يُقال «أقلّ من دقيقة».
     */
    public static function human(?int $minutes): string
    {
        if ($minutes === null || $minutes < 0) {
            return '—';
        }

        if ($minutes === 0) {
            return 'أقلّ من دقيقة';
        }

        $hours = intdiv($minutes, 60);
        $rest = $minutes % 60;

        if ($hours === 0) {
            return $rest . ' د';
        }

        return $rest === 0
            ? $hours . ' س'
            : $hours . ' س ' . $rest . ' د';
    }
}

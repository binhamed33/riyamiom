    /**
     * المداخل التي يمسّها السؤال — بمطابقة كلماتها الدالة.
     *
     * @return array<int, array<string, mixed>>
     */
    public static function matching(string $question): array
    {
        $q = self::normalize($question);
        $hits = [];

        foreach (self::references() as $ref) {
            foreach ($ref['keywords'] as $kw) {
                if (str_contains($q, self::normalize($kw))) {
                    $hits[] = $ref;
                    break;
                }
            }
        }

        return $hits;
    }

    /**
     * نصّ المراجع المطابقة، جاهز للحقن في تعليمة النظام.
     * فارغٌ إن لم يطابق شيء — وحينها يلتزم المساعد بحدّ «لا أختلق».
     */
    public static function contextFor(string $question): string
    {
        $hits = self::matching($question);

        if ($hits === []) {
            return '';
        }

        $lines = array_map(
            static fn ($r) => "- {$r['law']} ({$r['decree']}): {$r['principle']}",
            $hits
        );

        return "مراجع قانونية عُمانية موثوقة ذات صلة بالسؤال (استشهد بها بدقة، ولا تتجاوزها إلى أرقام مواد لم تُذكر هنا):\n"
            . implode("\n", $lines);
    }

    private static function normalize(string $text): string
    {
        // توحيد الألف والهمزات والتاء المربوطة حتى تطابق «دعوى» و«دعوة»
        return str_replace(
            ['أ', 'إ', 'آ', 'ى', 'ة', 'ـ'],
            ['ا', 'ا', 'ا', 'ي', 'ه', ''],
            mb_strtolower(trim($text))
        );
    }

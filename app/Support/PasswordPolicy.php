<?php

namespace App\Support;

use Illuminate\Validation\Rules\Password;

/**
 * سياسة كلمة المرور.
 *
 * كانت الشرط الوحيد ستّة أحرف بلا قيد آخر — في نظام يحفظ ملفات قضايا
 * وبيانات موكّلين، كلمة مرور مثل «123456» تُقبل. القاعدة موحّدة هنا فلا
 * تختلف من شاشة إلى أخرى.
 *
 * ما لا تفعله: لا تمسّ كلمات المرور القائمة. الشرط يسري على ما يُكتب
 * بعد اليوم فقط — لا أحد يُطرد من حسابه بسبب هذا التغيير.
 */
class PasswordPolicy
{
    public static function rules(): Password
    {
        return Password::min(8)
            ->letters()      // حرف واحد على الأقل
            ->mixedCase()    // كبير وصغير
            ->numbers()      // رقم
            ->symbols();     // رمز
    }

    /** رسائل بالعربية تشرح ما ينقص بدل «كلمة المرور غير صالحة». */
    public static function messages(string $field = 'password'): array
    {
        return [
            "{$field}.min" => 'كلمة المرور يجب ألّا تقلّ عن ٨ أحرف.',
            "{$field}.letters" => 'كلمة المرور يجب أن تحتوي على حرف واحد على الأقل.',
            "{$field}.mixed" => 'كلمة المرور يجب أن تحتوي على حرف كبير وحرف صغير.',
            "{$field}.numbers" => 'كلمة المرور يجب أن تحتوي على رقم واحد على الأقل.',
            "{$field}.symbols" => 'كلمة المرور يجب أن تحتوي على رمز مثل @ أو # أو !.',
        ];
    }
}
